//! The body of Clone Snapshot (NGSI-LD clause 5.16.2): a snapshot document without queries, naming the clone and
//! choosing its settings.

use crate::{
    model::{BuildError, Duration, KeyValuePair, RawJson, UrlDraft},
    snapshot::{Problem, SnapshotId, settings::Settings},
    subscription::{DocumentType, writer::push},
};
use bon::bon;
use jstrict::{Object, Value as Json};

/// What Clone Snapshot sends (clause 5.16.2.3): "a JSON-LD document conforming to the Snapshot data type [...] but
/// without" the details of the queries, and, as Table 5.2.41-1 says, without the queries themselves, which the
/// clone copies from the snapshot it clones.
///
/// It holds the `id` of the clone, generated by the broker when absent (clause 5.16.2.4), and the settings of the
/// clone. It is written `{"id", "type": "Snapshot", ...}`, and only written.
///
/// ```
/// use iri_rs::iri;
/// use ngsi_ld::snapshot::SnapshotClone;
///
/// let clone = SnapshotClone::builder().id(iri!("urn:ngsi-ld:Snapshot:2")).lifetime("P1D".parse()?).priority(3).build()?;
/// assert_eq!(
///     clone.render().to_string(),
///     r#"{"id":"urn:ngsi-ld:Snapshot:2","type":"Snapshot","snapshotLifetime":"P1D","snapshotPriority":3}"#
/// );
/// # Ok::<(), anyhow::Error>(())
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SnapshotClone {
    /// The `id` of the clone.
    id: Option<SnapshotId>,
    /// The settings of the clone.
    settings: Settings,
}

#[bon]
impl SnapshotClone {
    /// Starts the builder of the body of Clone Snapshot; every member is optional.
    ///
    /// # Errors
    ///
    /// `build()` returns [`BuildError`] listing a priority outside 1 to 10 and an endpoint that is not a URL (Table
    /// 5.2.41-1).
    #[builder]
    pub fn new(
        #[builder(into)] id: Option<SnapshotId>,
        lifetime: Option<Duration>,
        priority: Option<u8>,
        #[builder(into)] endpoint: Option<UrlDraft>,
        #[builder(with = |pairs: impl IntoIterator<Item = KeyValuePair>| pairs.into_iter().collect())] receiver_info: Option<Vec<KeyValuePair>>,
    ) -> Result<Self, BuildError<Problem>> {
        let mut problems = Vec::new();
        let settings = Settings::from_builder(lifetime, priority, endpoint, receiver_info, &mut problems);
        BuildError::finish(problems, Self { id, settings })
    }
}

impl SnapshotClone {
    /// Returns the `id` the clone is given; `None` lets the broker generate one.
    #[must_use]
    pub const fn id(&self) -> Option<&SnapshotId> {
        self.id.as_ref()
    }

    /// Writes the body: `id`, `type`, then the settings in the order of Table 5.2.41-1.
    #[must_use]
    pub fn render(&self) -> RawJson {
        RawJson::from_json(Json::Object(self.to_object()))
    }

    /// Writes the body without an `@context`, which the request pipeline delivers (clause 6.3.5).
    pub(crate) fn to_object(&self) -> Object {
        let mut object = Object::new();
        push(&mut object, "id", self.id.as_ref().map(|id| Json::from(id.as_str())));
        object.push("type".into(), Json::from(<&str>::from(DocumentType::Snapshot)));
        self.settings.write(&mut object);
        object
    }
}
