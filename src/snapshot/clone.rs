//! The body of Clone Snapshot (NGSI-LD clause 5.16.2): a snapshot document without queries, naming the clone and
//! choosing its settings.

use crate::{
    model::{BuildError, DocumentError, Duration, KeyValuePair, RawJson, UrlDraft, reader::parse_json},
    snapshot::{Problem, SnapshotId, reader::read_snapshot_clone, settings::Settings},
    subscription::{DocumentType, ReadErrorKind, writer::push},
};
use bon::bon;
use jstrict::{Object, Value as Json};

/// What Clone Snapshot sends: the settings of the clone, without its queries.
///
/// NGSI-LD clause 5.16.2.3 describes it as "a JSON-LD document conforming to the Snapshot data type [...] but without"
/// the details of the queries, and, as Table 5.2.41-1 says, it is without the queries themselves, which the clone
/// copies from the snapshot it clones.
///
/// It holds the `id` of the clone, generated by the broker when absent (clause 5.16.2.4), and the settings of the
/// clone. It is written `{"id", "type": "Snapshot", ...}`, and read by [`SnapshotClone::parse`].
///
/// ```
/// use iri_rs::iri;
/// use ngsi_ld::snapshot::SnapshotClone;
///
/// let clone = SnapshotClone::builder()
///     .id(iri!("urn:ngsi-ld:Snapshot:2"))
///     .lifetime("P1D".parse()?)
///     .priority(3)
///     .build()?;
/// assert_eq!(
///     clone.render().to_string(),
///     concat!(
///         r#"{"id":"urn:ngsi-ld:Snapshot:2","type":"Snapshot","#,
///         r#""snapshotLifetime":"P1D","snapshotPriority":3}"#
///     )
/// );
/// # Ok::<(), anyhow::Error>(())
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SnapshotClone {
    /// The `id` of the clone.
    pub(super) id: Option<SnapshotId>,
    /// The settings of the clone.
    pub(super) settings: Settings,
}

#[bon]
impl SnapshotClone {
    /// Starts the builder of the body of Clone Snapshot; every member is optional.
    ///
    /// # Errors
    ///
    /// `build()` returns [`BuildError`] listing a priority outside 1 to 10 and an endpoint that is not a URL (Table
    /// 5.2.41-1).
    #[builder]
    pub fn new(
        #[builder(into)] id: Option<SnapshotId>,
        lifetime: Option<Duration>,
        priority: Option<u8>,
        #[builder(into)] endpoint: Option<UrlDraft>,
        #[builder(with = |pairs: impl IntoIterator<Item = KeyValuePair>| pairs.into_iter().collect())] receiver_info: Option<Vec<KeyValuePair>>,
    ) -> Result<Self, BuildError<Problem>> {
        let mut problems = Vec::new();
        let settings = Settings::from_builder(lifetime, priority, endpoint, receiver_info, &mut problems);
        BuildError::finish(problems, Self { id, settings })
    }
}

impl SnapshotClone {
    /// Returns the `id` the clone is given; `None` lets the broker generate one.
    #[must_use]
    pub const fn id(&self) -> Option<&SnapshotId> {
        self.id.as_ref()
    }

    /// Writes the body: `id`, `type`, then the settings in the order of Table 5.2.41-1.
    #[must_use]
    pub fn render(&self) -> RawJson {
        RawJson::from_json(Json::Object(self.to_object()))
    }

    /// Reads the body of Clone Snapshot.
    ///
    /// Clause 5.16.2.3 asks for a Snapshot "without" its queries, so `snapshotQueries`,
    /// `snapshotTemporalQueries` and the members only a broker writes (Table 5.2.41-2) are refused, and `type`
    /// is required (Table 5.2.41-1). An `@context` is checked and not kept: the binding delivers it (clause 6.3.5).
    ///
    /// ```
    /// use ngsi_ld::snapshot::SnapshotClone;
    ///
    /// let clone = SnapshotClone::parse(
    ///     r#"{"id":"urn:ngsi-ld:Snapshot:2","type":"Snapshot","snapshotPriority":3}"#,
    /// )?;
    /// assert_eq!(
    ///     clone.id().map(|id| id.as_str()),
    ///     Some("urn:ngsi-ld:Snapshot:2")
    /// );
    /// # Ok::<(), anyhow::Error>(())
    /// ```
    ///
    /// # Errors
    ///
    /// Returns [`DocumentError`] naming the member at fault: a missing `type`, a priority outside 1 to 10, an
    /// `endpoint` that is not a URL, and a member Table 5.2.41-1 does not list for a clone.
    pub fn parse(text: &str) -> Result<Self, DocumentError<ReadErrorKind<Problem>>> {
        read_snapshot_clone(parse_json(text)?)
    }

    /// Writes the body without an `@context`, which the request pipeline delivers (clause 6.3.5).
    pub(crate) fn to_object(&self) -> Object {
        let mut object = Object::new();
        push(&mut object, "id", self.id.as_ref().map(|id| Json::from(id.as_str())));
        object.push("type".into(), Json::from(<&str>::from(DocumentType::Snapshot)));
        self.settings.write(&mut object);
        object
    }
}
